export function randomHueShift(random = Math.random): number {
    return Math.floor(random() * 361) - 180;
}

export function randomSeedWord(random = Math.random): string {
    return SEED_WORDS[Math.floor(random() * SEED_WORDS.length)] ?? 'seed';
}
