// Tailwind generates only the classes it finds whole in source files:
// https://tailwindcss.com/docs/detecting-classes-in-source-files#dynamic-class-names
import { breakpoints, frame, text } from '../src/design/tokens';

const prefixes = ['', ...breakpoints.map((breakpoint) => `${breakpoint}:`)].join(',');
const lines = [frame, text].flatMap((maps) =>
    Object.entries(maps).map(([prop, map]) => {
        const classes = [...new Set(Object.values(map as Record<string, string>).flatMap((value) => value.split(' ')))];
        return `/* ${prop} */\n@source inline("{${prefixes}}{${classes.join(',')}}");`;
    }),
);

await Bun.write(
    new URL('../src/design/tokens.css', import.meta.url),
    `/* Generated by scripts/design-tokens.ts from src/design/tokens.ts; run \`bun run design:tokens\` after changing the maps. */\n${lines.join('\n')}\n`,
);
