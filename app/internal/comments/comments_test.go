package comments

import (
	"go/parser"
	"go/token"
	"maps"
	"slices"
	"testing"
)

func checkSource(t *testing.T, filename, src string) Report {
	t.Helper()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filename, src, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	return Check(fset, file)
}

func lines(positions []token.Position) []int {
	var lines []int
	for _, pos := range positions {
		lines = append(lines, pos.Line)
	}
	return lines
}

func TestCheck(t *testing.T) {
	tests := []struct {
		name     string
		filename string
		src      string
		counted  []int
		nolint   []int
	}{
		{
			name:    "every comment line counts, block comments once",
			src:     "package a\n\n// one\n// two\nvar x = 1 /* three\nfour */\n",
			counted: []int{3, 4, 5},
		},
		{
			name:    "doc comments on exported identifiers count",
			src:     "package a\n\n// F does things.\nfunc F() {}\n",
			counted: []int{3},
		},
		{
			name: "compiler and tool directives are not comments",
			src:  "//go:build linux\n\npackage a\n\n//go:generate stringer\n//go:embed x.txt\nvar x string\n\n//lint:file-ignore U1000 reason\n",
		},
		{
			name: "a group linking upstream stays",
			src:  "package a\n\n// SQLite rejects this, see\n// https://docs.example.com/issue/1\nvar x = 1\n",
		},
		{
			name:    "a link covers only its own group",
			src:     "package a\n\n// see https://docs.example.com/issue/1\n\n// unrelated\nvar x = 1\n",
			counted: []int{5},
		},
		{
			name:    "a comment at another column starts a new group",
			src:     "package a\n\nvar x = 1 // trailing\n// https://docs.example.com/issue/1\nvar y = 2\n",
			counted: []int{3},
		},
		{
			name:    "links to Morgenblau's own domains and repos are not upstream",
			src:     "package a\n\n// https://app.morgen.blue/about\n// https://github.com/hfrdmnk/morgenblau/issues/1\n// https://tangled.org/@owner.example/morgenblau\nvar x = 1\n",
			counted: []int{3, 4, 5},
		},
		{
			name: "license headers stay",
			src:  "// Copyright 2026 Example Author\n// SPDX-License-Identifier: MIT\n\npackage a\n",
		},
		{
			name:    "license words after the package clause count",
			src:     "package a\n\n// Copyright notice\nvar x = 1\n",
			counted: []int{3},
		},
		{
			name:   "nolint is banned even next to a link",
			src:    "package a\n\nvar x = 1 //nolint:unused\nvar y = 2 // nolint // https://docs.example.com/issue/1\n",
			nolint: []int{3, 4},
		},
		{
			name: "generated files are skipped",
			src:  "// Code generated by sqlc. DO NOT EDIT.\n\npackage a\n\n// note\nvar x = 1\n",
		},
		{
			name:     "Output blocks in example tests are skipped",
			filename: "a_test.go",
			src:      "package a\n\nfunc ExampleF() {\n\tprintln(1)\n\t// Output:\n\t// 1\n}\n\nfunc TestF() {\n\t// Output: 1\n}\n",
			counted:  []int{10},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			filename := tt.filename
			if filename == "" {
				filename = "a.go"
			}
			report := checkSource(t, filename, tt.src)
			if got := lines(report.Counted); !slices.Equal(got, tt.counted) {
				t.Errorf("counted lines = %v, want %v", got, tt.counted)
			}
			if got := lines(report.Nolint); !slices.Equal(got, tt.nolint) {
				t.Errorf("nolint lines = %v, want %v", got, tt.nolint)
			}
		})
	}
}

func TestPruneOnlyLowersCounts(t *testing.T) {
	baseline := map[string]int{"lowered.go": 3, "over.go": 2, "deleted.go": 1}
	counts := map[string]int{"lowered.go": 1, "over.go": 5, "new.go": 4}
	want := map[string]int{"lowered.go": 1, "over.go": 2}
	if got := Prune(baseline, counts); !maps.Equal(got, want) {
		t.Errorf("Prune = %v, want %v", got, want)
	}
}
